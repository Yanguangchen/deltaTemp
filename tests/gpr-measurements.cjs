const assert=require('node:assert/strict');
const P=require('../gpr-annotator/prompt.js');
const axis=(unit,a,b,first=100,second=900)=>({unit,firstPosition:first,secondPosition:second,firstValue:a,secondValue:b});
const point={x:500,y:500};
let calibration={horizontal:axis('m',10,110),vertical:axis('m',0,20)};
assert.deepEqual(P.measurePoint(calibration,point),{alongM:60,depthM:10,timeNs:null,basis:'Read from m depth axis'});
assert.equal(P.measurePoint({...calibration,horizontal:axis('ft',0,100)},point).alongM,15.24);
assert.equal(P.measurePoint({...calibration,vertical:axis('in',0,20)},point).depthM,0.254);
assert.equal(P.measurePoint({...calibration,horizontal:axis('m',100,0)},point).alongM,50);
assert.equal(P.measurePoint(calibration,{x:0,y:999}).alongM,null);
assert.equal(P.measurePoint(calibration,{x:0,y:999}).depthM,null);
assert.equal(P.measurePoint({...calibration,vertical:axis('m',0,20,100,100)},point).depthM,null);
assert.equal(P.measurePoint({...calibration,horizontal:axis('unknown',0,100)},point).alongM,null);
calibration={horizontal:axis('m',0,100),vertical:axis('ns',0,400),velocityMPerNs:0.1,timeZeroKnown:true,timeZeroNs:0};
assert.equal(P.measurePoint(calibration,point).depthM,10);
assert.equal(P.measurePoint(calibration,point,0.08).depthM,8);
assert.equal(P.measurePoint({...calibration,timeZeroNs:20},point).depthM,9);
assert.equal(P.measurePoint({...calibration,timeZeroKnown:false},point).depthM,null);
assert.equal(P.measurePoint({...calibration,velocityMPerNs:0},point).depthM,null);
assert.equal(P.measurePoint({...calibration,velocityMPerNs:0},point).timeNs,200);
assert.equal(P.measurePoint({...calibration,timeZeroNs:201},point).depthM,null);
assert.equal(P.measurePoint(null,point).depthM,null);
assert.equal(P.validVelocity(0.31),false);assert.equal(P.validVelocity(''),false);
const response=object=>({candidates:[{content:{parts:[{text:JSON.stringify(object)}]}}]});
const annotations=[{label:'Hyperbola — possible utility',point,curve:[{x:100,y:800},point,{x:2000,y:800}],note:'Coherent limbs',confidence:0.7}];
const parsed=P.parseResponse(response({calibration,annotations}),{velocityMPerNs:0.08});
assert.equal(parsed[0].curve.length,2);assert.equal(parsed[0].velocityMPerNs,0.08);
assert.equal(P.measurePoint(parsed[0].calibration,parsed[0].point,parsed[0].velocityMPerNs).depthM,8);
assert.deepEqual(P.parseResponse(response({calibration,annotations:[]})),[]);
assert.throws(()=>P.parseResponse(response({annotations:{}})),/invalid annotation/);
const request=P.buildRequest({mimeType:'image/png',base64:'fixture',focus:'concrete slab'});
assert(request.contents[0].parts[1].text.includes('concrete slab'));
assert.equal(request.generationConfig.responseSchema,P.RESPONSE_SCHEMA);
console.log('Passed: metric/imperial axes, reversed axis, cropped ranges, missing calibration, two-way time, velocity override, time zero, no-target response and shared request schema.');
